//! 句式文法。
//!
//! 黑话的句式很固定："以 X 为抓手""围绕 X""通过 X""为了 X""把 X 落实""全面推进 X"……
//! 把它们写成一个上下文无关文法（第 2 章的写法），终结符是词典给每个词分的**类别**，不是具体的词——
//! 所以词典怎么扩充，文法都不用改。
//!
//! 这个文法有大量歧义（"业务 壁垒"是一个名词组还是两个？修饰语修饰谁？），所以每条产生式带一个**代价**，
//! 加权 Earley 分析直接找出总代价最小的那棵树：
//! - 每多一个"块"代价 10：尽量少切块，一个块就是一个完整的意思；
//! - 没有动词的块、"话题 + 动词"的块额外加代价：优先把名词当宾语；
//! - 修饰语当名词用、情态词放进谓词里加 1：优先让修饰语修饰后面的动词、情态词跟着主语。

use bsc_grammar::grammar::Grammar;

pub const CLAUSE_GRAMMAR: &str = "\
分句 -> 前置 主体 | 主体
前置 -> 主语 | 主语 情态 | 情态 | 名组 情态
主体 -> 块 | 块 主体
块 -> 手段 | 焦点 | 途径 | 目的 | 动作 | 连接 | 修饰 块
手段 -> 以 名组 为 名组 | 以 名组 作为 名组
焦点 -> 围绕 名组
途径 -> 通过 名组 | 在 名组 | 通过 谓词 名组
目的 -> 为了 名组 | 为 名组 | 为了 谓词 | 为了 谓词 名组
动作 -> 谓词 | 谓词 名组
     | 把 名组 作为 名组 | 把 名组 谓词 | 把 名组 谓词 名组 | 把 名组
     | 让 名组 谓词 | 让 名组 谓词 名组 | 让 名组
     | 名组 谓词 | 名组 谓词 名组
     | 名组
谓词 -> 动 | 修饰 谓词 | 情态 谓词 | 动 谓词 | 动 并列 谓词
名组 -> 名项 | 名项 名组 | 名组 并列 名组
名项 -> 名 | 修饰 | 的 | 主语
";

/// 产生式的代价（见模块说明）。
pub fn cost(g: &Grammar, p: usize) -> u32 {
    let prod = &g.productions[p];
    let lhs = g.name(prod.lhs);
    let first = prod.rhs.first().map(|&s| g.name(s));
    match (lhs, first, prod.rhs.len()) {
        ("块", Some("修饰"), _) => 0,
        ("块", _, _) => 10,
        ("谓词", Some("情态"), _) => 1,
        ("动作", Some("名组"), 1) => 8,
        ("动作", Some("让" | "把"), 2) => 8,
        ("动作", Some("名组"), _) => 3,
        ("前置", Some("名组"), _) => 2,
        ("名项", Some("修饰"), _) => 1,
        ("名项", Some("主语"), _) => 1,
        _ => 0,
    }
}

/// 支持的句式，诊断里列给用户看。
pub const PATTERNS: &str = "以 X 为 Y、围绕 X、通过 X / 在 X、为了 X、把 X + 动词、让 X + 动词、动词 + 宾语，以及它们的组合（前面可以有\"我们要\"这样的主语和情态词）";
